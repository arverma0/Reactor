function licenseText(dir) {
  const files = readdirSync(dir)
    .filter((f) => /^(licen[cs]e|copying|notice)/i.test(f) && !/-mpl/i.test(f))
    .sort();
  if (files.length === 0) throw new Error(`No license file in ${dir}`);
  return files.map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim()).join("\n\n");
}

function studioPackages() {
  const lock = JSON.parse(readFileSync(join(studio, "package-lock.json"), "utf8"));
  const groups = new Map();
  for (const [path, meta] of Object.entries(lock.packages)) {
    const name = path.slice(path.lastIndexOf("node_modules/") + "node_modules/".length);
    // Type declarations are erased at build time and never ship.
    if (!path || meta.dev || name.startsWith("@types/")) continue;
    const text = licenseText(join(studio, path));
    const group = groups.get(text) ?? { license: meta.license, names: [] };
    group.names.push(`${name} ${meta.version}`);
    groups.set(text, group);
  }
  return [...groups.entries()]
    .map(([text, { license, names }]) => ({ text, license, names: names.sort() }))
    .sort((a, b) => a.names[0].localeCompare(b.names[0]));
}

const fence = (text) => "````text\n" + text.trim() + "\n````";

