//   npm run notices            rewrite the file
//   npm run notices -- --check fail if the file is out of date
// Studio's runtime npm dependencies come from package-lock.json and node_modules (run `npm ci` first).
// The .NET section is maintained by hand below; update it when Directory.Packages.props changes.
